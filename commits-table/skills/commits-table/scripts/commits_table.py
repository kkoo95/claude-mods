#!/usr/bin/env python3
"""Build and splice the `## Commits` table of a GitHub pull request description.

Subcommands:
  commits <owner/repo> <pr>                  JSON list of the PR's commits, oldest first
  splice <body-file> <section-file>          print the body with its `## Commits` section replaced or inserted
  rewrite <body-file> <new-file>             print <new-file> followed by the attribution footer of <body-file>
  keep <body-file>                           JSON of what a rewrite must carry over: footer, checklists, references

Only REST calls through `gh api` are used, so it also works where GitHub GraphQL is blocked.
"""
import json
import re
import subprocess
import sys

TICKET_PREFIX = re.compile(r'^\s*\[[^\]]+\]\s*')
CONVENTIONAL = re.compile(r'^(\w+)(?:\(([^)]+)\))?!?$')
FOOTER = re.compile(r'^(🤖 Generated with|https://claude\.ai/code/|---\s*$|_Generated by)', re.M)
HEADING = re.compile(r'^## ', re.M)
SECTION = re.compile(r'^## Commits\s*$', re.M)


def gh_json(*args):
    out = subprocess.run(['gh', 'api', *args], check=True, capture_output=True, text=True).stdout
    return json.loads(out)


def commits(repo, pr):
    pages, page = [], 1
    while True:
        batch = gh_json(f'repos/{repo}/pulls/{pr}/commits?per_page=100&page={page}')
        pages += batch
        if len(batch) < 100:
            break
        page += 1
    rows = []
    for c in pages:
        subject = c['commit']['message'].split('\n', 1)[0]
        title = TICKET_PREFIX.sub('', subject)
        area, _, rest = title.partition(': ')
        conventional = CONVENTIONAL.match(area) if rest else None
        if conventional:
            area = conventional.group(2) or conventional.group(1)
        detail = gh_json(f'repos/{repo}/commits/{c["sha"]}')
        rows.append({
            'sha': c['sha'],
            'short': c['sha'][:7],
            'url': f'https://github.com/{repo}/pull/{pr}/commits/{c["sha"]}',
            'subject': subject,
            'area': area if rest else '',
            'title': rest or title,
            'files': [f['filename'] for f in detail.get('files', [])],
            'additions': detail['stats']['additions'],
            'deletions': detail['stats']['deletions'],
            'empty': not detail.get('files'),
            'merge': len(c.get('parents', [])) > 1,
        })
    return rows


def splice(body, section):
    section = section.strip('\n') + '\n'
    match = SECTION.search(body)
    if match:
        nxt = HEADING.search(body, match.end())
        foot = FOOTER.search(body, match.end())
        ends = [m.start() for m in (nxt, foot) if m]
        end = min(ends) if ends else len(body)
        return body[:match.start()] + section + '\n' + body[end:].lstrip('\n')
    foot = FOOTER.search(body)
    if foot:
        head = body[:foot.start()].rstrip('\n')
        return head + '\n\n' + section + '\n' + body[foot.start():]
    return body.rstrip('\n') + '\n\n' + section


def footer(body):
    match = FOOTER.search(body)
    return body[match.start():].strip('\n') + '\n' if match else ''


def rewrite(body, new):
    new = new.strip('\n') + '\n'
    foot = footer(body)
    return new + ('\n' + foot if foot and foot.strip() not in new else '')


REFERENCE = re.compile(r'(?i)\b(?:close[sd]?|fix(?:e[sd])?|resolve[sd]?|refs?)\s+[\w./-]*#\d+|\bsc-\d+\b|https?://\S*(?:shortcut\.com|atlassian\.net|linear\.app)\S*')
CHECKLIST = re.compile(r'^\s*[-*] \[[ xX]\] .+$', re.M)


def prose_words(text):
    match = SECTION.search(text)
    if match:
        nxt = HEADING.search(text, match.end())
        text = text[:match.start()] + (text[nxt.start():] if nxt else '')
    return len(text.split())


def keep(body):
    head = body[:FOOTER.search(body).start()] if FOOTER.search(body) else body
    return {
        'footer': footer(body),
        'checklists': CHECKLIST.findall(head),
        'references': sorted(set(REFERENCE.findall(head))),
        'headings': re.findall(r'^#{1,3} .+$', head, re.M),
        'words': prose_words(head),
    }


def main(argv):
    if len(argv) == 3 and argv[0] == 'commits':
        json.dump(commits(argv[1], argv[2]), sys.stdout, indent=1, ensure_ascii=False)
        print()
    elif len(argv) == 3 and argv[0] == 'splice':
        body = open(argv[1], encoding='utf-8').read()
        section = open(argv[2], encoding='utf-8').read()
        sys.stdout.write(splice(body, section))
    elif len(argv) == 3 and argv[0] == 'rewrite':
        body = open(argv[1], encoding='utf-8').read()
        sys.stdout.write(rewrite(body, open(argv[2], encoding='utf-8').read()))
    elif len(argv) == 2 and argv[0] == 'keep':
        json.dump(keep(open(argv[1], encoding='utf-8').read()), sys.stdout, indent=1, ensure_ascii=False)
        print()
    else:
        sys.stderr.write(__doc__)
        return 2
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
